#!/usr/bin/env python3
"""Blind worksheet and grading analysis for ADF.

Two commands, matching `docs/plans/cde/GRADING.md`:

  worksheet  build a blind grading file plus a separate score key
  analyze    tally verdicts, band agreement, signed bias, and self-consistency

The blind file never contains D, the band, or the dimensions. That separation is
the whole point: a grade given while the model's answer is visible cannot detect
the model's bias.

    python3 tools/cde/cde_grade.py worksheet \
        --corpus "asterisma new testing suite" \
        --scores docs/audits/evidence/adf-149-scores-2026-10-29.json \
        --out docs/audits/evidence/adf-grades-worksheet-2026-10-29 \
        --window 0 --excerpt-chars 520

    python3 tools/cde/cde_grade.py analyze \
        --grades docs/audits/evidence/adf-grades-worksheet-2026-10-29.blind.tsv \
        --scores docs/audits/evidence/adf-grades-worksheet-2026-10-29.scores.tsv \
        --out docs/audits/evidence/adf-grade-report-2026-10-29.json
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import statistics
import sys
from pathlib import Path

import cde_extract

# Must match `bands` in the frozen reference exactly; a name mismatch here
# would silently drop every row from the bias sums.
BAND_ORDER = ["Light", "Moderate", "Demanding", "Heavy", "Very heavy"]
LABELS = ["OK", "TOO_LOW", "TOO_HIGH", "CANNOT_JUDGE"]
WS = re.compile(r"\s+")


def clean_excerpt(text: str, chars: int) -> str:
    flat = WS.sub(" ", text).strip()
    return flat[:chars]


def build_worksheet(args) -> int:
    scores = json.loads(Path(args.scores).read_text())
    rows = scores["rows"] if isinstance(scores, dict) else scores
    folder = Path(args.corpus).expanduser()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)

    wanted = None
    if args.files:
        wanted = {w.strip() for w in Path(args.files).read_text().splitlines() if w.strip()}

    blind_rows, key_rows = [], []
    for row in rows:
        if row.get("status") != "ok":
            continue
        if wanted is not None and row["file"] not in wanted:
            continue
        package = folder / row["file"]
        if not package.exists():
            print(f"missing package: {package}", file=sys.stderr)
            continue
        try:
            loaded = cde_extract.load_package(package)
            selected, _, _ = cde_extract.select_windows(
                loaded, count=args.windows, tokens_per_window=1200)
        except Exception as error:  # noqa: BLE001 - corpus is untrusted input
            print(f"  extract failed {row['file']}: {error}", file=sys.stderr)
            continue
        if args.window >= len(selected):
            print(f"  no window {args.window} for {row['file']}", file=sys.stderr)
            continue
        excerpt = clean_excerpt(selected[args.window]["text"], args.excerpt_chars)
        blind_rows.append({
            "file": row["file"], "title": row.get("title") or row["file"],
            "window": args.window, "excerpt": excerpt,
            "band_as_i_would_call_it": "",
            "verdict": "", "severity": "", "reason": "",
        })
        key_rows.append({
            "file": row["file"], "title": row.get("title") or row["file"],
            "score": row.get("score"), "band": row.get("band"),
            "interval_low": (row.get("interval") or [None, None])[0],
            "interval_high": (row.get("interval") or [None, None])[1],
            "windows_used": row.get("windows_used"),
            "sampled_share": row.get("sampled_share"),
        })
        if len(blind_rows) % 25 == 0:
            print(f"  {len(blind_rows)} excerpts", flush=True)

    write_tsv(out.with_suffix(".blind.tsv"), blind_rows)
    write_tsv(out.with_suffix(".scores.tsv"), key_rows)
    out.with_suffix(".md").write_text(render_worksheet(blind_rows, args.window))
    print(f"blind: {out.with_suffix('.blind.tsv')} ({len(blind_rows)} rows)")
    print(f"key:   {out.with_suffix('.scores.tsv')}")
    print(f"sheet: {out.with_suffix('.md')}")
    return 0


def write_tsv(path: Path, rows: list[dict]) -> None:
    if not rows:
        path.write_text("")
        return
    fields = list(rows[0])
    with path.open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fields, delimiter="\t",
                                quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def render_worksheet(rows: list[dict], window: int) -> str:
    lines = [
        "# ADF blind grading worksheet",
        "",
        "> Generated by `tools/cde/cde_grade.py worksheet`. Do not hand-edit;"
        " fill the verdicts in the companion `.blind.tsv` and rerun the tool.",
        "",
        f"Window index **{window}** for every book. `D`, the band and the",
        "dimensions are deliberately absent; they are in the companion",
        "`.scores.tsv` and must not be opened until grading is finished.",
        "",
        "Labels: `OK`, `TOO_LOW`, `TOO_HIGH`, `CANNOT_JUDGE`.",
        "See `docs/plans/cde/GRADING.md` §1 before the first row.",
        "",
    ]
    for i, row in enumerate(rows, 1):
        lines += [
            f"### {i}. {row['title']}",
            "",
            f"`{row['file']}`",
            "",
            f"> {row['excerpt']}",
            "",
            f"- band I would call it: `{row.get('band_as_i_would_call_it') or '__________'}`"
            "  (Light / Moderate / Demanding / Heavy / Very heavy)",
            f"- verdict: `{row['verdict'] or '__________'}`",
            "- severity:  ",
            "- reason:  ",
            "",
        ]
    return "\n".join(lines) + "\n"


def kappa(pairs: list[tuple[str, str]]) -> float | None:
    if not pairs:
        return None
    labels = sorted({a for a, _ in pairs} | {b for _, b in pairs})
    n = len(pairs)
    observed = sum(1 for a, b in pairs if a == b) / n
    expected = 0.0
    for label in labels:
        pa = sum(1 for a, _ in pairs if a == label) / n
        pb = sum(1 for _, b in pairs if b == label) / n
        expected += pa * pb
    if expected >= 1.0:
        return 1.0
    return (observed - expected) / (1 - expected)


def read_tsv(path: Path) -> list[dict]:
    with path.open(newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def analyse(args) -> int:
    grades = read_tsv(Path(args.grades))
    key = {r["file"]: r for r in read_tsv(Path(args.scores))}
    second = ({r["file"]: r for r in read_tsv(Path(args.second_pass))}
              if args.second_pass else {})

    resolved, unresolved, unjudgeable, ungraded = [], [], [], []
    for row in grades:
        file = row["file"]
        verdict = (row.get("verdict") or "").strip().upper()
        if verdict not in LABELS and verdict != "UNRESOLVED":
            ungraded.append(file)
            continue
        if verdict == "CANNOT_JUDGE":
            unjudgeable.append(file)
            continue
        if verdict == "UNRESOLVED":
            unresolved.append(file)
            continue
        resolved.append((file, verdict))

    def band_index(band):
        try:
            return BAND_ORDER.index(band)
        except (ValueError, TypeError):
            return None

    tally = {label: 0 for label in LABELS}
    for row in grades:
        verdict = (row.get("verdict") or "").strip().upper()
        if verdict in tally:
            tally[verdict] += 1

    # Band distance, not verdict sign. A row graded one band low is a smaller
    # error than one graded four bands low, and the verdict alphabet alone
    # cannot tell them apart. `band_as_i_would_call_it` is the grader's own
    # band; when it is absent the verdict's sign is used as a fallback and the
    # report says which basis it used.
    calls = {(r.get("file") or ""): (r.get("band_as_i_would_call_it") or "").strip()
             for r in grades}
    distance_basis = any(calls.get(f) in BAND_ORDER for f, _ in resolved)

    signed = []
    within_one = []
    by_band: dict[str, list[int]] = {}
    for file, verdict in resolved:
        info = key.get(file)
        if not info:
            continue
        predicted = band_index(info.get("band"))
        if predicted is None:
            continue
        called = band_index(calls.get(file)) if distance_basis else None
        if called is not None:
            delta = called - predicted
        else:
            delta = {"TOO_LOW": 1, "TOO_HIGH": -1, "OK": 0}[verdict]
        signed.append(delta)
        within_one.append(abs(delta) <= 1)
        by_band.setdefault(info["band"], []).append(delta)

    first = {r["file"]: (r.get("verdict") or "").strip().upper() for r in grades}
    pairs = [(first[file], (second[file].get("verdict") or "").strip().upper())
             for file in second
             if first.get(file) in LABELS
             and (second[file].get("verdict") or "").strip().upper() in LABELS]
    agree = sum(1 for a, b in pairs if a == b)

    report = {
        "formula": "asterisma-difficulty-formula@0.3",
        "graded_rows": len(grades),
        "resolved_rows": len(resolved),
        "cannot_judge_rows": len(unjudgeable),
        "unresolved_rows": len(unresolved),
        "ungraded_rows": len(ungraded),
        "cannot_judge_rate": round(len(unjudgeable) / max(1, len(grades)), 4),
        "verdict_tally": tally,
        "band_agreement_within_one": round(sum(within_one) / max(1, len(within_one)), 4),
        "band_distance_basis": "grader's own band" if distance_basis else "verdict sign (fallback)",
        "mean_band_delta": (round(statistics.mean(signed), 4) if signed else None),
        "median_band_delta": (round(statistics.median(signed), 4) if signed else None),
        "max_under_call": (max(signed) if signed else None),
        "max_over_call": (min(signed) if signed else None),
        "rows_per_band": {band: len(vals) for band, vals in by_band.items()},
        "signed_bias_by_band": {
            band: round(statistics.mean(vals), 4)
            for band, vals in sorted(by_band.items(), key=lambda kv: BAND_ORDER.index(kv[0]))
            if vals
        },
        "self_consistency": {
            "paired_rows": len(pairs),
            "agreement": round(agree / len(pairs), 4) if pairs else None,
            "cohens_kappa": (round(kappa(pairs), 4) if kappa(pairs) is not None else None),
            "label": "self-consistency (one grader, two passes); not inter-rater",
        } if pairs else None,
        "interpretation_limit": (
            "Document grades locate suspicious outputs. They are not a reading-time "
            "measurement and cannot certify accuracy; see GRADING.md §0."
        ),
    }
    text = json.dumps(report, indent=2, sort_keys=False)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text + "\n")
    print(text)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="command", required=True)

    ws = sub.add_parser("worksheet")
    ws.add_argument("--corpus", required=True)
    ws.add_argument("--scores", required=True)
    ws.add_argument("--out", required=True, help="path stem, no suffix")
    ws.add_argument("--windows", type=int, default=12)
    ws.add_argument("--window", type=int, default=0)
    ws.add_argument("--excerpt-chars", type=int, default=520)
    ws.add_argument("--files", default=None, help="optional newline list of filenames")

    an = sub.add_parser("analyze")
    an.add_argument("--grades", required=True)
    an.add_argument("--scores", required=True)
    an.add_argument("--second-pass", default=None)
    an.add_argument("--out", default=None)

    args = ap.parse_args()
    if args.command == "worksheet":
        return build_worksheet(args)
    return analyse(args)


if __name__ == "__main__":
    sys.exit(main())
